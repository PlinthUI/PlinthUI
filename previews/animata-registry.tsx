"use client"

import dynamic from "next/dynamic"
import type { ComponentType } from "react"
import type { PreviewProps } from "./types"

function Loading() {
  return <div className="h-40 w-full max-w-sm animate-pulse rounded-lg bg-muted" aria-hidden />
}

/**
 * Every Animata component renders its own default export as the preview, inside
 * a stage. Backgrounds and other components that fill their parent get a box
 * with a definite height, so they have something to fill. The rest are centered.
 */
function inStage(Comp: ComponentType<Record<string, unknown>>, mode: "fill" | "center"): ComponentType<PreviewProps> {
  function Stage() {
    return mode === "fill" ? (
      <div className="relative h-72 w-full overflow-hidden rounded-lg border">
        <Comp />
      </div>
    ) : (
      <div className="relative flex min-h-56 w-full items-center justify-center">
        <Comp />
      </div>
    )
  }
  return Stage
}

const load = (loader: () => Promise<{ default: ComponentType<never> }>, mode: "fill" | "center") =>
  inStage(dynamic(loader, { ssr: false, loading: Loading }) as unknown as ComponentType<Record<string, unknown>>, mode)

